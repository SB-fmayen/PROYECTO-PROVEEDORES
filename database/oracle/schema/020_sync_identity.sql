-- Ejecutar como ADMIN_CU_PROVEEDORES en FREEPDB1, sin escrituras concurrentes.
-- Incidencia verificada: CENTRO_COSTO generó ID=1 aunque existen IDs hasta 20.
-- Realinea generadores IDENTITY; no modifica valores existentes, PK/FK ni triggers.
-- DDL hace COMMIT implícito. No ejecutar dentro de una transacción de negocio.
-- Referencia: https://docs.oracle.com/en/database/oracle/oracle-database/19/sqlrf/ALTER-TABLE.html
WHENEVER SQLERROR EXIT SQL.SQLCODE;
DECLARE
  total NUMBER;
BEGIN
  IF USER <> 'ADMIN_CU_PROVEEDORES' OR SYS_CONTEXT('USERENV','CON_NAME') <> 'FREEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20001,'Ejecutar como propietario en FREEPDB1.');
  END IF;
  SELECT COUNT(*) INTO total FROM USER_TAB_IDENTITY_COLS
  WHERE TABLE_NAME IN ('PROVEEDOR','CENTRO_COSTO','USUARIO','DOCUMENTO_COMPRA','DETALLE_DOCUMENTO_COMPRA','PAGO_BANCARIO')
    AND GENERATION_TYPE='BY DEFAULT';
  IF total <> 6 THEN RAISE_APPLICATION_ERROR(-20002,'Metadatos identity distintos del esquema verificado.'); END IF;
END;
/
ALTER TABLE ADMIN_CU_PROVEEDORES.PROVEEDOR MODIFY (IDPROVEEDOR GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999999999999999999999 NOCYCLE CACHE 20 NOORDER));
ALTER TABLE ADMIN_CU_PROVEEDORES.CENTRO_COSTO MODIFY (IDCENTROCOSTO GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999999999999999999999 NOCYCLE CACHE 20 NOORDER));
ALTER TABLE ADMIN_CU_PROVEEDORES.USUARIO MODIFY (IDUSUARIO GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999999999999999999999 NOCYCLE CACHE 20 NOORDER));
ALTER TABLE ADMIN_CU_PROVEEDORES.DOCUMENTO_COMPRA MODIFY (IDDOCUMENTOCOMPRA GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999999999999999999999 NOCYCLE CACHE 20 NOORDER));
ALTER TABLE ADMIN_CU_PROVEEDORES.DETALLE_DOCUMENTO_COMPRA MODIFY (IDDETALLE GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999999999999999999999 NOCYCLE CACHE 20 NOORDER));
ALTER TABLE ADMIN_CU_PROVEEDORES.PAGO_BANCARIO MODIFY (IDPAGO GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999999999999999999999 NOCYCLE CACHE 20 NOORDER));
