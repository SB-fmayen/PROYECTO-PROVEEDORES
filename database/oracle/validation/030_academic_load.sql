SELECT 'RETENCION_ISR' AS TABLA, COUNT(*) AS TOTAL FROM ADMIN_CU_PROVEEDORES.RETENCION_ISR
UNION ALL SELECT 'CONTRASENA_PAGO', COUNT(*) FROM ADMIN_CU_PROVEEDORES.CONTRASENA_PAGO
UNION ALL SELECT 'DOCUMENTO_POR_LIQUIDAR', COUNT(*) FROM ADMIN_CU_PROVEEDORES.DOCUMENTO_POR_LIQUIDAR
UNION ALL SELECT 'ASIENTO_CONTABLE', COUNT(*) FROM ADMIN_CU_PROVEEDORES.ASIENTO_CONTABLE;
SELECT PERIODO, SUM(DEBE) AS DEBE, SUM(HABER) AS HABER
FROM ADMIN_CU_PROVEEDORES.ASIENTO_CONTABLE
WHERE CUENTACONTABLE IN ('DEMO-CXP', 'DEMO-BANCOS')
GROUP BY PERIODO;
SELECT COUNT(*) AS REFERENCIAS_INCOHERENTES
FROM ADMIN_CU_PROVEEDORES.DOCUMENTO_POR_LIQUIDAR l
JOIN ADMIN_CU_PROVEEDORES.DOCUMENTO_COMPRA d ON d.IDDOCUMENTOCOMPRA=l.IDDOCUMENTOCOMPRA
JOIN ADMIN_CU_PROVEEDORES.PAGO_BANCARIO p ON p.IDPAGO=l.IDPAGO
WHERE d.IDPROVEEDOR<>p.IDPROVEEDOR;
SELECT NOMBRE_TABLA, OPERACION, COUNT(*) AS EVENTOS
FROM ADMIN_CU_PROVEEDORES.LOG_AUDITORIA_ODC
WHERE DATOS_NUEVOS LIKE '%academic-seed-2026-11-07%'
GROUP BY NOMBRE_TABLA, OPERACION;
