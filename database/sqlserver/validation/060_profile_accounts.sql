SELECT u.USUARIO_LOGIN,u.ESTADO,r.NOMBRE_ROL,p.NOMBRE_PERFIL,m.RUTA,
  pm.PUEDE_VER,pm.PUEDE_CREAR,pm.PUEDE_EDITAR,pm.PUEDE_ELIMINAR
FROM SEGURIDAD_PROVEEDORES.USUARIO u
JOIN SEGURIDAD_PROVEEDORES.USUARIO_ROL ur ON ur.ID_USUARIO=u.ID_USUARIO AND ur.ESTADO=1
JOIN SEGURIDAD_PROVEEDORES.ROL r ON r.ID_ROL=ur.ID_ROL AND r.ESTADO=1
JOIN SEGURIDAD_PROVEEDORES.ROL_PERFIL rp ON rp.ID_ROL=r.ID_ROL AND rp.ESTADO=1
JOIN SEGURIDAD_PROVEEDORES.PERFIL p ON p.ID_PERFIL=rp.ID_PERFIL AND p.ESTADO=1
JOIN SEGURIDAD_PROVEEDORES.PERFIL_MENU pm ON pm.ID_PERFIL=p.ID_PERFIL
JOIN SEGURIDAD_PROVEEDORES.MENU m ON m.ID_MENU=pm.ID_MENU AND m.ESTADO=1
WHERE u.USUARIO_LOGIN IN ('consulta_cpp','operador_cpp','tesoreria_cpp','auditor_cpp')
ORDER BY u.USUARIO_LOGIN,m.ORDEN;
